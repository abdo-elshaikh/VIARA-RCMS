// Disposable PostgreSQL only. Never connects to an existing cluster or loads .env.
const fs = require('node:fs');
const path = require('node:path');
const net = require('node:net');
const crypto = require('node:crypto');
const { spawnSync } = require('node:child_process');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
process.env.NODE_ENV = 'test';
require(path.join(root, 'backend/tests/setupEnv'));
const { Pool } = require(path.join(root, 'backend/node_modules/pg'));
const express = require(path.join(root, 'backend/node_modules/express'));
const request = require(path.join(root, 'backend/node_modules/supertest'));
const bcrypt = require(path.join(root, 'backend/node_modules/bcrypt'));
const jwt = require(path.join(root, 'backend/node_modules/jsonwebtoken'));
const { encrypt } = require(path.join(root, 'backend/src/utils/crypto'));
const { patientLogin } = require(path.join(root, 'backend/src/controllers/portalController'));
const { doctorLogin } = require(path.join(root, 'backend/src/controllers/doctorPortalController'));
const { refresh, logout } = require(path.join(root, 'backend/src/controllers/authController'));
const { authenticateToken, configureAuthDatabase } = require(path.join(root, 'backend/src/middleware/authMiddleware'));
const portalRoutes = require(path.join(root, 'backend/src/routes/portalRoutes'));
require(path.join(root, 'backend/src/services/settingsService')).getAll = async () => ({});
const pgBin = process.env.VIARA_TEST_PG_BIN || (process.platform === 'win32' ? 'C:/Program Files/PostgreSQL/18/bin' : '/usr/lib/postgresql/18/bin');
const binary = name => path.join(pgBin, name + (process.platform === 'win32' ? '.exe' : ''));
const run = (name, args) => {
    const result = spawnSync(binary(name), args, { encoding: 'utf8', windowsHide: true, timeout: 60000, ...(name === 'pg_ctl' ? { stdio: 'ignore' } : {}) });
    if (result.status !== 0) throw new Error(`${name} failed: ${result.error?.message || result.stderr || result.stdout}`);
};
const freePort = () => new Promise((resolve, reject) => {
    const server = net.createServer(); server.on('error', reject);
    server.listen(0, '127.0.0.1', () => { const port = server.address().port; server.close(() => resolve(port)); });
});
const check = (condition, message) => { assert.ok(condition, message); checks++; };
let checks = 0, pool, started = false, dataDir;
const uid = () => crypto.randomUUID();
const patient = uid(), other = uid(), doctor = uid();
const main = async () => {
    const scratch = path.join(root, 'scratch/remote-access-validation'); fs.mkdirSync(scratch, { recursive: true });
    const workspace = fs.mkdtempSync(path.join(scratch, 'postgres-'));
    dataDir = path.join(workspace, 'data');
    run('initdb', ['-D', dataDir, '-U', 'viara_test', '--auth=trust', '--encoding=UTF8', '--locale=C']);
    const port = await freePort();
    run('pg_ctl', ['-D', dataDir, '-l', path.join(workspace, 'postgres.log'), '-o', `-h 127.0.0.1 -p ${port}`, '-w', 'start']);
    started = true;
    pool = new Pool({ host: '127.0.0.1', port, user: 'viara_test', database: 'postgres', max: 5 });
    await pool.query(`
        CREATE TABLE users (user_id uuid PRIMARY KEY, current_session_id uuid, role text, email text, full_name text, is_active boolean, must_change_password boolean);
        CREATE TABLE patients (patient_id uuid PRIMARY KEY, current_session_id uuid, mrn text, password_hash text, patient_status text, first_name_enc text, last_name_enc text, portal_failed_login_attempts int DEFAULT 0, portal_locked_until timestamptz);
        CREATE TABLE referring_doctors (doctor_id uuid PRIMARY KEY, current_session_id uuid, email text, full_name text, is_active boolean, portal_is_active boolean, portal_password_hash text, portal_last_login timestamptz, portal_failed_login_attempts int DEFAULT 0, portal_locked_until timestamptz);
        CREATE TABLE refresh_tokens (token_id uuid PRIMARY KEY DEFAULT gen_random_uuid(), user_id uuid, patient_id uuid, doctor_id uuid, session_id uuid, token_hash text UNIQUE, expires_at timestamptz, revoked boolean DEFAULT false, revoked_at timestamptz, revoked_reason text, parent_token_id uuid, ip_address text, user_agent text, last_used_at timestamptz);
        CREATE TABLE appointments (appointment_id uuid PRIMARY KEY, patient_id uuid);
        CREATE TABLE examinations (exam_id uuid PRIMARY KEY, patient_id uuid);
        CREATE TABLE invoices (invoice_id uuid PRIMARY KEY, patient_id uuid, appointment_id uuid, exam_id uuid, invoice_number text, invoice_status text, generated_at timestamptz DEFAULT now(), subtotal_amount numeric DEFAULT 100, discount_amount numeric DEFAULT 0, tax_amount numeric DEFAULT 0, total_amount numeric DEFAULT 100, insurance_covered_amount numeric DEFAULT 0, patient_payable_amount numeric DEFAULT 100);
        CREATE TABLE invoice_items (invoice_id uuid, description text, quantity numeric, unit_price numeric, total_amount numeric, created_at timestamptz);
        CREATE TABLE payments (invoice_id uuid, payment_status text, amount numeric, transaction_date timestamptz, method text);
        CREATE TABLE refunds (invoice_id uuid, status text, amount numeric);
        CREATE TABLE credit_notes (invoice_id uuid, patient_amount numeric, reversed_at timestamptz);
        CREATE TABLE patient_portal_audit (patient_id uuid, event_type text, resource_type text, resource_id uuid, details jsonb, ip_address text, user_agent text);
        CREATE TABLE patient_portal_documents (document_id uuid, patient_id uuid, is_patient_visible boolean, file_url text, title text, document_type text);
        CREATE TABLE documents (document_id uuid, patient_id uuid, is_deleted boolean, file_path text, file_name text, mime_type text);
    `);
    const password = 'Synthetic-test-password'; const hash = await bcrypt.hash(password, 4);
    await pool.query('INSERT INTO patients(patient_id,mrn,password_hash,patient_status,first_name_enc,last_name_enc) VALUES ($1,$2,$3,$4,$5,$6),($7,$8,$3,$4,$5,$6)', [patient, 'TEST-A', hash, 'Active', encrypt('\u0623\u062d\u0645\u062f'), encrypt('\u0645\u062d\u0645\u062f'), other, 'TEST-B']);
    await pool.query('INSERT INTO referring_doctors(doctor_id,email,full_name,is_active,portal_is_active,portal_password_hash) VALUES ($1,$2,$3,true,true,$4)', [doctor, 'synthetic@example.test', 'Test doctor', hash]);
    configureAuthDatabase(pool);
    const app = express(); app.use(express.json());
    app.post('/api/portal/login', patientLogin(pool));
    app.post('/api/doctor-portal/login', doctorLogin(pool));
    app.post('/api/portal/auth/refresh', refresh(pool));
    app.post('/api/auth/refresh', refresh(pool));
    app.post('/api/portal/auth/logout', logout(pool));
    app.get('/api/portal/session-check', authenticateToken, (req, res) => res.json({ role: req.user.role }));
    app.use('/api', portalRoutes(pool));
    app.use((err, req, res, next) => { console.error('Synthetic API error:', err.message); res.status(err.statusCode || 500).json({ error: err.message }); });
    const login = agent => agent.post('/api/portal/login').send({ mrn: 'TEST-A', password }).expect(200);
    const authGet = (url, token) => request(app).get(url).set('Authorization', `Bearer ${token}`);
    for (const role of ['Patient', 'Doctor']) {
        const agent = request.agent(app);
        const loggedIn = role === 'Patient' ? await login(agent) : await agent.post('/api/doctor-portal/login').send({ email: 'synthetic@example.test', password }).expect(200);
        check(loggedIn.headers['set-cookie'].some(c => c.includes('Path=/api/portal;') && c.includes('HttpOnly')), `${role} cookie scope`);
        await authGet('/api/portal/session-check', loggedIn.body.token).expect(200); checks++;
        const refreshed = await agent.post('/api/portal/auth/refresh').send({}).expect(200); checks++;
        check(jwt.decode(refreshed.body.token).session_id === jwt.decode(loggedIn.body.token).session_id, `${role} refresh preserves session`);
        await agent.post('/api/portal/auth/logout').send({}).expect(200); checks++;
        await authGet('/api/portal/session-check', refreshed.body.token).expect(401); checks++;
        await agent.post('/api/portal/auth/refresh').send({}).expect(401); checks++;
        const ownerColumn = role === 'Patient' ? 'patient_id' : 'doctor_id';
        const tokens = await pool.query(`SELECT revoked FROM refresh_tokens WHERE ${ownerColumn}=$1`, [role === 'Patient' ? patient : doctor]);
        check(tokens.rows.length >= 2 && tokens.rows.every(r => r.revoked), `${role} entire rotated family revoked without bearer`);
    }
    const oldAgent = request.agent(app); const oldLogin = await login(oldAgent);
    const newAgent = request.agent(app); const newLogin = await login(newAgent);
    await oldAgent.post('/api/portal/auth/logout').send({}).expect(200);
    await authGet('/api/portal/session-check', newLogin.body.token).expect(200); checks++;
    await authGet('/api/portal/session-check', oldLogin.body.token).expect(401); checks++;
    const newCookie = newLogin.headers['set-cookie'].find(c => c.startsWith('portalRefreshToken=')).split(';')[0].replace('portalRefreshToken=', 'refreshToken=');
    const before = (await pool.query('SELECT count(*) FROM refresh_tokens WHERE revoked=false')).rows[0].count;
    await request(app).post('/api/auth/refresh').set('Cookie', newCookie).send({}).expect(403); checks++;
    check((await pool.query('SELECT count(*) FROM refresh_tokens WHERE revoked=false')).rows[0].count === before, 'wrong realm refresh does not revoke tokens');
    await pool.query('UPDATE referring_doctors SET is_active=false WHERE doctor_id=$1', [doctor]);
    await request(app).post('/api/doctor-portal/login').send({ email: 'synthetic@example.test', password }).expect(401); checks++;
    const invoice = uid(), foreignInvoice = uid(), conflictInvoice = uid(), voidInvoice = uid(), appointment = uid(), exam = uid();
    await pool.query('INSERT INTO appointments VALUES ($1,$2)', [appointment, other]);
    await pool.query('INSERT INTO examinations VALUES ($1,$2)', [exam, other]);
    await pool.query("INSERT INTO invoices(invoice_id,patient_id,invoice_number,invoice_status,appointment_id,exam_id) VALUES ($1,$2,'OWN','Paid',NULL,NULL),($3,$4,'OTHER','Paid',NULL,NULL),($5,$2,'CONFLICT','Paid',$6,$7),($8,$2,'VOID','Voided',NULL,NULL)", [invoice, patient, foreignInvoice, other, conflictInvoice, appointment, exam, voidInvoice]);
    const pdf = await authGet(`/api/portal/invoices/${invoice}/pdf`, newLogin.body.token).expect(200);
    check(pdf.body.subarray(0, 5).toString() === '%PDF-', 'real owner invoice produces PDF');
    fs.writeFileSync(path.join(workspace, 'invoice.pdf'), pdf.body);
    for (const rejected of [foreignInvoice, conflictInvoice, voidInvoice]) { await authGet(`/api/portal/invoices/${rejected}/pdf`, newLogin.body.token).expect(404); checks++; }
    const portalDocument = uid(), managedDocument = uid();
    await pool.query('INSERT INTO patient_portal_documents VALUES ($1,$2,true,$3,$4,$5)', [portalDocument, patient, `/api/documents/${managedDocument}/download`, 'Test', 'PDF']);
    await pool.query('INSERT INTO documents VALUES ($1,$2,false,$3,$4,$5)', [managedDocument, other, 'not-read.pdf', 'test.pdf', 'application/pdf']);
    await authGet(`/api/portal/documents/${portalDocument}/download`, newLogin.body.token).expect(404); checks++;
    await pool.query('UPDATE patient_portal_documents SET patient_id=$1 WHERE document_id=$2', [other, portalDocument]);
    await authGet(`/api/portal/documents/${portalDocument}/download`, newLogin.body.token).expect(404); checks++;
    const audit = await pool.query('SELECT event_type FROM patient_portal_audit');
    check(audit.rows.length === 1 && audit.rows[0].event_type === 'InvoiceDownloaded', 'denied downloads create no successful download audit');
    fs.writeFileSync(path.join(scratch, 'portal-postgres-results.json'), JSON.stringify({ checks, passed: true, postgres: '18', fixtureOnly: true, pdf: path.join(workspace, 'invoice.pdf') }, null, 2));
    console.log(`PASS: ${checks} PostgreSQL + HTTP session/ownership checks (synthetic isolated cluster).`);
};
main().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => {
    configureAuthDatabase(undefined);
    if (pool) await pool.end();
    if (started) run('pg_ctl', ['-D', dataDir, '-m', 'fast', '-w', 'stop']);
});
