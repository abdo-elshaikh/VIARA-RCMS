'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const policy = JSON.parse(fs.readFileSync(path.join(root, 'portal/nginx/portal-api-policy.json'), 'utf8'));
const output = '# Generated by node scripts/generate-portal-api-policy.cjs. Do not edit.\n'
  + '# Include once at nginx http{} scope. Route filtering supplements backend authorization.\n'
  + 'map "$request_method:$uri" $viara_portal_api_allowed {\n    default 0;\n'
  + policy.map(({path: route, methods}) => `    "~^(?:${methods.join('|')}):${route}/?$" 1;`).join('\n')
  + '\n}\n'
  + '\n# Do not log query strings, Authorization, referrers, or legacy report-link tokens.\n'
  + 'map $uri $viara_portal_log_path {\n    default $uri;\n'
  + '    ~^/api/public/final-report/ /api/public/final-report/[redacted];\n}\n'
  + 'log_format viara_portal \'$remote_addr [$time_local] "$request_method $viara_portal_log_path" $status $body_bytes_sent $request_time\';\n';
const targets = ['portal/nginx/portal-api-policy.conf', 'deploy/remote-access/nginx/portal-api-policy.conf'];
for (const target of targets) {
  const filename = path.join(root, target);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(filename) || fs.readFileSync(filename, 'utf8') !== output) {
      throw new Error(`${target} is stale: run node scripts/generate-portal-api-policy.cjs`);
    }
  } else fs.writeFileSync(filename, output);
}
console.log(`Portal API policy: ${targets.length} files ${process.argv.includes('--check') ? 'verified' : 'generated'}.`);
